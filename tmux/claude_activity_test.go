var trBase = time.Date(2026, 11, 3, 2, 45, 0, 0, time.UTC)

func TestLastWorkAt(t *testing.T) {
	turnEnd := trBase.Add(-19 * time.Hour)
	tests := []struct {
		name  string
		lines []string
		want  time.Time
		found bool
	}{
		{
			// 2026-11-03 의 사고: 쉬던 세션마다 /theme 이 들어가 상태 파일의 시각이 그 순간으로 바뀌었다.
			// 마지막 작업은 그 전날 끝난 턴이다.
			name: "프롬프트의 로컬 명령은 작업이 아니다",
			lines: append([]string{
				trUser(turnEnd.Add(-time.Minute), "고쳐 줘", false),
				trAssistant(turnEnd, false),
				trSystem(turnEnd, "stop_hook_summary"),
				trSystem(turnEnd, "turn_duration"),
				trSystem(turnEnd.Add(5*time.Minute), "away_summary"),
			}, trTheme(trBase)...),
			want: turnEnd, found: true,
		},
		{
			name: "중단도 작업의 끝이다",
			lines: []string{
				trAssistant(turnEnd, false),
				trToolResult(turnEnd.Add(time.Second)),
				trUser(turnEnd.Add(10*time.Minute), "[Request interrupted by user for tool use]", false),
			},
			want: turnEnd.Add(10 * time.Minute), found: true,
		},
		{
			name: "셸 모드(!)와 하위 에이전트 줄은 세지 않는다",
			lines: []string{
				trAssistant(turnEnd, false),
				trUser(turnEnd.Add(time.Minute), "<bash-input>ls</bash-input>", false),
				trUser(turnEnd.Add(time.Minute), "<bash-stdout>a b</bash-stdout><bash-stderr></bash-stderr>", false),
				trAssistant(turnEnd.Add(2*time.Minute), true),
			},
			want: turnEnd, found: true,
		},
		{
			name: "본문에 태그를 인용한 프롬프트는 작업이다",
			lines: []string{
				trAssistant(turnEnd, false),
				trUser(turnEnd.Add(time.Minute), "이 줄 봐: <command-name>/theme</command-name>", false),
			},
			want: turnEnd.Add(time.Minute), found: true,
		},
		{
			name:  "로컬 명령뿐이면 찾지 못한다",
			lines: trTheme(trBase),
			found: false,
		},
		{
			// 쓰다 만 마지막 줄은 건너뛴다.
			name: "잘린 마지막 줄",
			lines: []string{
				trAssistant(turnEnd, false),
				`{"type":"user","timestamp":"` + trTime(trBase) + `","message":{"content":"반쯤`,
			},
			want: turnEnd, found: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "s.jsonl")
			writeTranscriptFile(t, path, tt.lines)
			got, found := lastWorkAt(path)
			if found != tt.found || !got.Equal(tt.want) {
				t.Errorf("lastWorkAt = %v, %v; want %v, %v", got, found, tt.want, tt.found)
			}
		})
	}
}

// 마지막 작업 줄 뒤에 첫 꼬리(64KB)보다 긴 다른 줄들이 있어도 거슬러 올라가 찾는다.
// 실제 기록에서는 끝에서 50KB 떨어진 경우까지 봤다.
func TestLastWorkAtReachesPastALongTail(t *testing.T) {
	turnEnd := trBase.Add(-time.Hour)
	lines := []string{trAssistant(turnEnd, false)}
	big := `{"type":"file-history-snapshot","snapshot":"` + strings.Repeat("x", 4096) + `"}`
	for range 64 { // 256KB
		lines = append(lines, big)
	}
	path := filepath.Join(t.TempDir(), "s.jsonl")
	writeTranscriptFile(t, path, lines)

	got, found := lastWorkAt(path)
	if !found || !got.Equal(turnEnd) {
		t.Errorf("lastWorkAt = %v, %v; want %v", got, found, turnEnd)
	}
}

// 결과는 파일이 그대로인 동안만 재사용한다. 새 턴이 붙으면 다시 읽는다.
func TestLastWorkAtRereadsAGrownFile(t *testing.T) {
	first := trBase.Add(-time.Hour)
	path := filepath.Join(t.TempDir(), "s.jsonl")
	writeTranscriptFile(t, path, []string{trAssistant(first, false)})
	if got, _ := lastWorkAt(path); !got.Equal(first) {
		t.Fatalf("first read = %v, want %v", got, first)
	}

	f, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := f.WriteString(trAssistant(trBase, false) + "\n"); err != nil {
		t.Fatal(err)
	}
	f.Close()

	if got, _ := lastWorkAt(path); !got.Equal(trBase) {
		t.Errorf("after append = %v, want %v", got, trBase)
	}
}

