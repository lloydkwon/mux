// 픽스처 줄은 실제 기록(Claude Code 2.1.312)에서 본 모양을 줄였다. 쓰는 필드만 남겼다.

func trTime(t time.Time) string { return t.UTC().Format("2006-01-02T15:04:05.000Z") }

func trUser(at time.Time, content string, meta bool) string {
	b, _ := json.Marshal(map[string]any{
		"type": "user", "timestamp": trTime(at), "isMeta": meta, "isSidechain": false,
		"message": map[string]any{"role": "user", "content": content},
	})
	return string(b)
}

func trToolResult(at time.Time) string {
	b, _ := json.Marshal(map[string]any{
		"type": "user", "timestamp": trTime(at), "isSidechain": false,
		"message": map[string]any{"role": "user", "content": []map[string]any{
			{"type": "tool_result", "tool_use_id": "toolu_1", "content": "ok"},
		}},
	})
	return string(b)
}

func trAssistant(at time.Time, sidechain bool) string {
	b, _ := json.Marshal(map[string]any{
		"type": "assistant", "timestamp": trTime(at), "isSidechain": sidechain,
		"message": map[string]any{"role": "assistant", "content": []map[string]any{
			{"type": "text", "text": "끝났습니다"},
		}},
	})
	return string(b)
}

func trSystem(at time.Time, subtype string) string {
	b, _ := json.Marshal(map[string]any{
		"type": "system", "timestamp": trTime(at), "subtype": subtype, "isMeta": false,
	})
	return string(b)
}

// trTheme 은 프롬프트에서 /theme 을 고른 흔적이다. 세 줄 모두 user 줄이다.
func trTheme(at time.Time) []string {
	return []string{
		trUser(at, "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", true),
		trUser(at, "<command-name>/theme</command-name>\n            <command-message>theme</command-message>\n            <command-args></command-args>", false),
		trUser(at, "<local-command-stdout>Theme set to dark</local-command-stdout>", false),
	}
}

func writeTranscriptFile(t *testing.T, path string, lines []string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatalf("create transcript dir: %v", err)
	}
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatalf("write transcript: %v", err)
	}
}

