// --claude 목록도 같은 규칙이다 — 그 목록도 UI 의 recent 정렬(sessionAge)을 거친다.
func TestClaudeSessionsDateIdleByItsLastWork(t *testing.T) {
	statusAt := trBase.UnixMilli()
	turnEnd := trBase.Add(-19 * time.Hour)
	files := map[string]string{
		"1.json": runFile(1, "id-idle", "/w/one", "idle", "one", "", 1000, statusAt),
		"2.json": runFile(2, "id-busy", "/w/two", "busy", "two", "", 1000, statusAt),
	}
	withClaudeSessions(t, files, nil, func() {
		writeSessionTranscript(t, "id-idle", "/w/one", append([]string{trAssistant(turnEnd, false)}, trTheme(trBase)...))
		writeSessionTranscript(t, "id-busy", "/w/two", []string{trAssistant(turnEnd, false)})

		runs := ClaudeSessions()
		idle, ok := runNamed(runs, "one")
		if !ok {
			t.Fatalf("no row for the idle conversation: %+v", runs)
		}
		if !idle.Session.AILastActive.Equal(turnEnd) {
			t.Errorf("idle AILastActive = %v, want %v", idle.Session.AILastActive, turnEnd)
		}
		if !idle.Session.AISince.Equal(trBase) {
			t.Errorf("idle AISince = %v, want the status file's %v", idle.Session.AISince, trBase)
		}
		if busy, _ := runNamed(runs, "two"); !busy.Session.AILastActive.IsZero() {
			t.Errorf("busy AILastActive = %v, want zero", busy.Session.AILastActive)
		}
	})
}

